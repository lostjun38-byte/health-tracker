export function getQuote(offset = 0) {
  const now = new Date()
  const start = new Date(now.getFullYear(), 0, 0)
  const dayOfYear = Math.floor((now - start) / 86400000)
  const idx = ((dayOfYear + offset) % QUOTES.length + QUOTES.length) % QUOTES.length
  return QUOTES[idx]
}
